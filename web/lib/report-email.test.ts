import { createHmac } from "node:crypto";
import { describe, expect, it, vi } from "vitest";
import { deliverReport, emailAvailable, emailPayload, safeEmailReport, verifyEmailToken, type EmailSettings } from "./report-email";

const settings: EmailSettings = { apiKey: "re_test_secret", sender: "LytaScan <reports@lytaworks.com>", signingSecret: "a-secret-for-tests-with-at-least-32-characters" };
const report = {
  scan: { account_id: "111122223333", started_at: "2026-11-18T10:00:00Z", finished_at: "2026-11-18T10:01:00Z", regions: ["us-east-1"], checks_run: ["iam_root_mfa"] },
  findings: [{ check_id: "iam_root_mfa", title: "<script>bad()</script>", pillar: "security", severity: "critical", status: "fail", resource_arn: "arn:aws:iam::111122223333:root", resource_type: "account", region: "global", account_id: "111122223333", description: "Root MFA absent", remediation: "Enable MFA", scanned_at: "2026-11-18T10:00:30Z" }],
};
function incompleteReport() {
  return { scan: { ...report.scan, assessment: { version: "2.0.0", registry_version: "2.1.0", overall_score: null,
    evaluated_pillars: 0, planned_scopes: 2, completed_scopes: 1, critical_failures: 0,
    pillars: [{ pillar: "security", score: null, coverage: null, planned_scopes: 2, completed_scopes: 1 }] } },
    findings: [],
    scopes: [{ check_id: "iam_root_mfa", pillar: "security", region: "global", status: "complete" },
      { check_id: "ec2_imdsv2", pillar: "security", region: "us-east-1", status: "incomplete", reason_codes: ["request_failed"] }],
    execution: { source: "temporary_session", stopped: false, settled_scopes: 2 } };
}

function token(changes: Record<string, unknown> = {}) {
  const payload = Buffer.from(JSON.stringify({ account_id: "111122223333", email: "owner@example.com", expires_at: Math.floor(Date.now() / 1000) + 3600, nonce: "0123456789abcdef0123456789abcdef", ...changes })).toString("base64url");
  return `${payload}.${createHmac("sha256", settings.signingSecret).update(payload).digest("base64url")}`;
}
function request(body: object, origin = "https://lytascan.lytaworks.com") {
  return new Request("https://lytascan.lytaworks.com/api/report-email", { method: "POST", headers: { origin, "content-type": "application/json" }, body: JSON.stringify(body) });
}

describe("report email capabilities", () => {
  it("requires a provider, sender and signing secret", () => {
    expect(emailAvailable(settings)).toBe(true);
    expect(emailAvailable({ ...settings, apiKey: "" })).toBe(false);
    expect(emailAvailable({ ...settings, signingSecret: "short" })).toBe(false);
    expect(emailAvailable({ ...settings, sender: "bad\r\nBcc: other@example.com" })).toBe(false);
  });
  it("rejects expired and tampered email capabilities", () => {
    expect(verifyEmailToken(token(), settings.signingSecret).email).toBe("owner@example.com");
    expect(() => verifyEmailToken(token({ expires_at: 1 }), settings.signingSecret)).toThrow();
    expect(() => verifyEmailToken(`${token()}bad`, settings.signingSecret)).toThrow();
  });
  it("verifies a capability produced by the actual Python issuer", () => {
    // Generated by api.ephemeral._email_token with a fixed clock/nonce and the
    // fictional test secret above; the supplied mixed-case email normalizes.
    const pythonToken = "eyJhY2NvdW50X2lkIjoiMTExMTIyMjIzMzMzIiwiZW1haWwiOiJvd25lckBleGFtcGxlLmNvbSIsImV4cGlyZXNfYXQiOjE4OTM0NTk2MDAsIm5vbmNlIjoiMDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWYifQ.IZdbWFpyqFHSVe7Bql1AKKAxJo0y6HkcvU-LGTrp6kA";
    expect(verifyEmailToken(pythonToken, settings.signingSecret, Date.UTC(2030, 0, 1))).toEqual({
      account_id: "111122223333", email: "owner@example.com", expires_at: 1893459600,
      nonce: "0123456789abcdef0123456789abcdef",
    });
  });
  it("projects report fields and escapes finding HTML", () => {
    const safe = safeEmailReport({ ...report, credentials: { secretAccessKey: "NEVER_ATTACH" } });
    const payload = emailPayload(safe, "owner@example.com", settings.sender);
    expect(JSON.stringify(payload)).not.toContain("NEVER_ATTACH");
    expect(payload.html).not.toContain("<script>");
    expect(payload.html).toContain("&lt;script&gt;");
    expect(JSON.parse(Buffer.from(payload.attachments[0].content, "base64").toString())).toEqual(safe);
  });
  it("preserves coverage and warns about incomplete scopes even with no error findings", () => {
    const original = incompleteReport();
    const safe = safeEmailReport({ ...original, execution: { ...original.execution, secret: "NEVER_ATTACH" },
      scopes: original.scopes.map((scope) => ({ ...scope, credentials: "NEVER_ATTACH" })),
      scan: { ...original.scan, assessment: { ...original.scan.assessment, credentials: "NEVER_ATTACH" } } });
    const payload = emailPayload(safe, "owner@example.com", settings.sender);
    const attached = JSON.parse(Buffer.from(payload.attachments[0].content, "base64").toString());
    expect(attached.scopes).toEqual(original.scopes);
    expect(attached.execution).toEqual(original.execution);
    expect(attached.scan.assessment).toEqual(original.scan.assessment);
    expect(JSON.stringify(attached)).not.toContain("NEVER_ATTACH");
    expect(payload.subject).toContain("incomplete report");
    expect(payload.text).toContain("1 of 2 planned scopes completed successfully");
    expect(payload.text).toContain("1 of 2 scan scopes did not complete");
    expect(payload.html).toContain("this report does not confirm a clean AWS posture");
  });
  it("does not imply complete coverage when scope metadata is absent", () => {
    expect(emailPayload(safeEmailReport(report), "owner@example.com", settings.sender).text).toContain("Coverage could not be confirmed");
  });
  it("rejects malformed or inconsistent scope and assessment metadata", () => {
    const original = incompleteReport();
    expect(() => safeEmailReport({ ...original, scopes: [...original.scopes, original.scopes[0]] })).toThrow();
    expect(() => safeEmailReport({ ...original, scopes: original.scopes.map((scope) => ({ ...scope, status: "bogus" })) })).toThrow();
    expect(() => safeEmailReport({ ...original, execution: { ...original.execution, settled_scopes: 3 } })).toThrow();
    expect(() => safeEmailReport({ ...original, scan: { ...original.scan, assessment: { ...original.scan.assessment, completed_scopes: 2 } } })).toThrow();
    expect(() => safeEmailReport({ ...original, scopes: Array(601).fill(original.scopes[0]) })).toThrow();
    expect(() => safeEmailReport({ ...original, findings: Array(5001).fill(report.findings[0]) })).toThrow();
  });
  it("rejects cross-account findings", () => {
    expect(() => safeEmailReport({ ...report, findings: [{ ...report.findings[0], account_id: "444455556666" }] })).toThrow();
  });
});

describe("email delivery", () => {
  it("does not send without a configured provider or a same-origin request", async () => {
    const provider = vi.fn();
    expect((await deliverReport(request({}), { ...settings, apiKey: "" }, provider)).status).toBe(503);
    expect((await deliverReport(request({}, "https://other.example"), settings, provider)).status).toBe(403);
    expect(provider).not.toHaveBeenCalled();
  });
  it("rejects recipient substitution and unsigned reports", async () => {
    const provider = vi.fn();
    expect((await deliverReport(request({ email: "other@example.com", report, email_token: token() }), settings, provider)).status).toBe(400);
    expect((await deliverReport(request({ email: "owner@example.com", report }), settings, provider)).status).toBe(400);
    expect(provider).not.toHaveBeenCalled();
  });
  it("enforces the body limit with and without a declared content length", async () => {
    const provider = vi.fn();
    const oversized = request({ padding: "x".repeat(2_000_001) });
    expect((await deliverReport(oversized, settings, provider)).status).toBe(413);
    const declared = request({});
    declared.headers.set("content-length", "2000001");
    expect((await deliverReport(declared, settings, provider)).status).toBe(413);
    expect(provider).not.toHaveBeenCalled();
  });
  it("attaches the complete sanitized report with a provider idempotency key", async () => {
    const provider = vi.fn().mockResolvedValue(Response.json({ id: "email-receipt" }));
    const result = await deliverReport(request({ email: "owner@example.com", report, email_token: token() }), settings, provider);
    expect(await result.json()).toEqual({ sent: true });
    const [url, options] = provider.mock.calls[0];
    expect(url).toBe("https://api.resend.com/emails");
    expect(options.headers["Idempotency-Key"]).toBe("lytascan-report/0123456789abcdef0123456789abcdef");
    expect(JSON.parse(options.body).to).toEqual(["owner@example.com"]);
    expect(JSON.parse(options.body).attachments).toHaveLength(1);
  });
  it("never exposes provider error messages or secrets", async () => {
    const provider = vi.fn().mockResolvedValue(Response.json({ message: "private-provider-details" }, { status: 401 }));
    const result = await deliverReport(request({ email: "owner@example.com", report, email_token: token() }), settings, provider);
    expect(result.status).toBe(502);
    expect(JSON.stringify(await result.json())).not.toMatch(/private-provider-details|re_test_secret/);
  });
});
